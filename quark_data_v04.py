"""Quark v0.4 data: fill-in-the-middle rows cut from ~265 real repos (no tests run), with repo context.

Repos: quark_repos_v04_clean.jsonl (the checked v0.4 list) plus v0.3's training repos from quark_repos.jsonl. The 10
held-out benchmark repos are never used, and any file identical to one of theirs is skipped (vendored copies).

Every row is {fim_prompt, oracle_middle, loss, ...}; train.py's fim-sft mode puts the loss on the fill only
(loss="middle") or on every token (loss="all"). Row kinds, mixed per repo:

  ast      a whole statement / block / function body (the v0.3 holes; the benchmark uses these)
  midline  the cursor sits inside a line: finish that line, sometimes plus a few more
  span     a random character range (may start and end mid-line), like Qwen's pretraining FIM
  empty    the code at the cursor is already complete: the right answer is to stop at once
  file     a whole chunk of a file split into prefix/middle/suffix, loss on every token (keeps it a code LM)

About a third of the hole rows also show other files of the same repo first (`<|file_sep|>path` + their API
skeletons, the files the target imports or is imported by), so Quark learns to use the repo's own helpers.

  uv run python quark_data_v04.py --rows 120000 --out fim_v04.jsonl
  uv run python quark_data_v04.py --rows 300 --repos 3 --out fim_v04_smoke.jsonl   # quick look

v0.5: the same rows, but the context is ctx_gather.py's name-based context (what an editor plugin sends: definitions of
the names near the cursor, the enclosing class, the file's outline, what the imports provide) in most hole rows:
  uv run python quark_data_v04.py --ctx names --ctx-share 0.7 --ctx-chars 4000 --tag v05 --seed 1 \\
      --rows 60000 --out fim_v05.jsonl
"""
import argparse
import collections
import concurrent.futures as cf
import hashlib
import json
import math
import random
import re
import subprocess
from pathlib import Path

from fim import FIM_MID, FIM_PRE, FIM_SEP, FIM_SUF
from repo_fim import HELDOUT, MAX_MIDDLE_CHARS, REPOS, SFT_ONLY, candidates
from repomap import extract_file_skeleton

EXT_LANG = {".py": "python", ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
            ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript", ".jsx": "javascript",
            ".h": "cpp", ".hpp": "cpp", ".hh": "cpp", ".hxx": "cpp", ".cpp": "cpp", ".cc": "cpp", ".cxx": "cpp"}
TEST_DIRS = {"test", "tests", "__tests__", "node_modules", "dist", "build", "vendor", "third_party", "__generated__"}
GENERATED = re.compile(r"auto-?generated|@generated|do not edit|generated by", re.I)
KINDS = {"ast": 0.33, "midline": 0.20, "span": 0.14, "empty": 0.05, "file": 0.28}
CTX_SHARE = 0.35  # hole rows that also show related repo files
LANG_WEIGHT = {"javascript": 1.6}  # Quark's weakest language (29% on the benchmark): more rows per repo
AI_TOOL_WEIGHT = 0.5  # AI-agent tooling repos are a third of the list; halve their share so they don't dominate
MAX_FILE_CHARS, MIN_FILE_LINES, MAX_LINE_CHARS = 150_000, 8, 400
FILE_CHUNK_CHARS = 7000  # "file" rows: ~2k tokens
CTX_CHARS = 3000  # repo context budget per row


def glob_regex(pattern: str) -> re.Pattern:
    """git-style glob -> regex over posix paths. `[` is literal (Next.js folders like `[slug]` are real names)."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?"); i += 3
        elif pattern.startswith("**", i):
            out.append(".*"); i += 2
        elif pattern[i] == "*":
            out.append("[^/]*"); i += 1
        elif pattern[i] == "?":
            out.append("[^/]"); i += 1
        else:
            out.append(re.escape(pattern[i])); i += 1
    return re.compile("".join(out))


def is_source(rel: str) -> bool:
    p = Path(rel)
    return (p.suffix in EXT_LANG and not p.name.endswith(".d.ts") and ".min." not in p.name
            and not any(part.lower() in TEST_DIRS for part in p.parts[:-1])
            and ".test." not in p.name and ".spec." not in p.name and not p.name.startswith("test_"))


def norm_hash(text: str) -> str:
    return hashlib.sha1(re.sub(r"\s+", "", text).encode("utf-8", "replace")).hexdigest()


def git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True).stdout.decode("utf-8", "replace")


def repo_files(root: Path, globs: list[str]) -> dict[str, str]:
    """{rel path: text} of the hand-written source files the globs pick, minus tests/generated/minified files."""
    pats = [glob_regex(g) for g in globs]
    out = {}
    for rel in git(root, "ls-files", "-z").split("\0"):
        if not rel or not is_source(rel) or not any(p.fullmatch(rel) for p in pats):
            continue
        try:
            text = (root / rel).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        lines = text.splitlines()
        if (len(text) > MAX_FILE_CHARS or len(lines) < MIN_FILE_LINES
                or max(map(len, lines)) > MAX_LINE_CHARS or GENERATED.search("\n".join(lines[:10]))):
            continue
        out[rel] = text.replace("\r\n", "\n")
    return out


# --- import graph (which repo files a file uses) ---------------------------------------------------------------------
_JS_REF = re.compile(r"""(?:\bfrom\s*|\bimport\s*\(?\s*|\brequire\s*\(\s*)['"]([^'"\n]+)['"]""")
_CPP_REF = re.compile(r'^\s*#\s*include\s*"([^"]+)"', re.M)
_PY_REF = re.compile(r"^\s*(?:from\s+(\.*)([\w.]*)\s+import\s+([\w*, ()]+)|import\s+([\w.]+))", re.M)
_JS_EXTS = ("", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", "/index.ts", "/index.tsx", "/index.js",
            "/index.jsx")


def _norm(path: str) -> str:
    parts = []
    for p in path.split("/"):
        if p == "..":
            if parts:
                parts.pop()
        elif p not in ("", "."):
            parts.append(p)
    return "/".join(parts)


def import_graph(files: dict[str, str]) -> dict[str, set[str]]:
    """{file: repo files it imports}: relative / `@/` JS-TS imports (`./x.js` may mean x.ts), Python modules (also
    under src/ layouts, relative imports included) and C++ `#include "..."`."""
    names = set(files)
    py_mod = {}  # dotted module name (every path suffix) -> file
    for f in sorted(names, key=lambda p: -p.count("/")):  # shorter paths win a tie
        if f.endswith(".py"):
            parts = f[:-3].split("/")
            if parts[-1] == "__init__":
                parts = parts[:-1]
            for i in range(len(parts)):
                py_mod[".".join(parts[i:])] = f
    by_tail = collections.defaultdict(list)  # C++: "dir/x.h" -> files ending with it
    for f in names:
        segs = f.split("/")
        for i in range(len(segs)):
            by_tail["/".join(segs[i:])].append(f)
    graph = {}
    for f, src in files.items():
        here = f.rsplit("/", 1)[0] if "/" in f else ""
        deps = set()
        if f.endswith(".py"):
            for dots, mod, what, plain in _PY_REF.findall(src):
                if dots:
                    base = here.split("/") if here else []
                    base = base[:len(base) - (len(dots) - 1)] if len(dots) > 1 else base
                    stem = "/".join(base + ([mod.replace(".", "/")] if mod else []))
                    cands = [f"{stem}.py", f"{stem}/__init__.py"] + [
                        f"{stem}/{w.strip()}.py" for w in what.strip("() ").split(",") if w.strip()]
                    deps |= {c for c in cands if c in names}
                else:
                    m = mod or plain
                    hit = py_mod.get(m) or py_mod.get(m.rsplit(".", 1)[0] if "." in m else "")
                    if hit:
                        deps.add(hit)
                    for w in what.strip("() ").split(",") if mod else ():
                        if py_mod.get(f"{mod}.{w.strip()}"):
                            deps.add(py_mod[f"{mod}.{w.strip()}"])
        elif f.endswith((".h", ".hpp", ".hh", ".hxx", ".cpp", ".cc", ".cxx")):
            for ref in _CPP_REF.findall(src):
                rel = _norm(f"{here}/{ref}")
                hit = rel if rel in names else (by_tail.get(ref) or [None])[0]
                if hit:
                    deps.add(hit)
        else:
            for ref in _JS_REF.findall(src):
                if ref.startswith("."):
                    stem = _norm(f"{here}/{ref}")
                elif ref.startswith(("@/", "~/")):
                    stem = ref[2:]
                else:
                    continue  # a package, not a repo file
                stem = re.sub(r"\.(m|c)?jsx?$", "", stem)
                for root in ("", "src/", "app/") if ref.startswith(("@/", "~/")) else ("",):
                    hit = next((root + stem + e for e in _JS_EXTS if root + stem + e in names), None)
                    if hit:
                        deps.add(hit)
                        break
        deps.discard(f)
        graph[f] = deps
    return graph


# --- prompt pieces ---------------------------------------------------------------------------------------------------
def cut_prefix(text: str, n: int) -> str:
    """The last ~n chars of `text`, starting at a line boundary (or all of it)."""
    if len(text) <= n:
        return text
    t = text[-n:]
    return t[t.find("\n") + 1:]


def cut_suffix(text: str, n: int) -> str:
    """The first ~n chars of `text`, ending at a line boundary."""
    if len(text) <= n:
        return text
    return text[:text.rfind("\n", 0, n) + 1]


def window_sizes(rng: random.Random, kind: str) -> tuple[int, int]:
    if rng.random() < 0.5:
        return 2400, 900  # the benchmark's window
    if kind != "empty" and rng.random() < 0.06:
        return rng.randint(300, 5000), 0  # typing at the end of a file
    return rng.randint(300, 5000), rng.randint(200, 2500)  # "empty" needs code after the cursor, or stopping is a guess


_DECL = re.compile(r"^(?:export\s+)?(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?"
                   r"(?:function\*?|class|interface|type|enum|namespace|module|const|let|var|struct|union|"
                   r"template|typedef|using|#define)\b")
_METHOD = re.compile(r"^(?:(?:public|private|protected|static|async|readonly|override|get|set|virtual|inline|"
                     r"constexpr|explicit|friend)\s+)*[A-Za-z_~][\w:<>,*&\s]*\([^;{}]*\)\s*(?:const\s*)?"
                     r"(?::\s*[^{=;]+)?\s*(?:override\s*)?[{;]?\s*$")
_NOT_METHOD = re.compile(r"^(?:if|for|while|switch|return|catch|else|do|try|new|await|throw|delete|case)\b")


def brace_skeleton(text: str) -> str:
    """Top-level declarations plus class-level method signatures, bodies left out (JS/TS/C++)."""
    out = []
    for ln in text.split("\n"):
        s = ln.strip()
        indent = len(ln) - len(ln.lstrip())
        if not s or s.startswith(("//", "/*", "*")) or indent > 4:
            continue
        if indent == 0 and (_DECL.match(s) or s.startswith(("import ", "#include"))) or (
                indent > 0 and _METHOD.match(s) and not _NOT_METHOD.match(s)):
            out.append(ln.rstrip()[:160].rstrip(" {") + (" {...}" if s.endswith("{") else ""))
    return "\n".join(out)


def skeleton(path: str, text: str) -> str:
    if len(text) <= 1500:
        return text  # small files: the whole thing
    if path.endswith(".py"):
        return extract_file_skeleton(path, text)
    return brace_skeleton(text)


def context_block(rng: random.Random, rel: str, files: dict[str, str], graph: dict[str, set[str]],
                  callers: dict[str, set[str]]) -> str:
    """`<|file_sep|>path\\nskeleton` for up to 4 related files (imports first, then importers, else same folder)."""
    near = sorted(graph.get(rel, set())) + sorted(callers.get(rel, set()) - graph.get(rel, set()))
    if not near:
        folder = rel.rsplit("/", 1)[0] if "/" in rel else ""
        near = [p for p in files if p != rel and (p.rsplit("/", 1)[0] if "/" in p else "") == folder]
        rng.shuffle(near)
    blocks, used = [], 0
    for nb in near[:4]:
        skel = skeleton(nb, files[nb]) or cut_suffix(files[nb], 800)
        block = f"{FIM_SEP}{nb}\n{skel.rstrip()}\n"
        if used + len(block) > CTX_CHARS:
            block = block[:CTX_CHARS - used]
            block = block[:block.rfind("\n") + 1]
            if not block.strip():
                break
        blocks.append(block)
        used += len(block)
    return "".join(blocks) + f"{FIM_SEP}{rel}\n" if blocks else ""


# --- hole pickers: each returns (prefix_text, middle, suffix_text) over the whole file, or None ----------------------
def hole_ast(rng, text, lang, state):
    spans = state.setdefault("ast", None)
    if spans is None:
        spans = state["ast"] = candidates(text, lang, f"v04:{rng.random()}")
    if not spans:
        return None
    lo, hi, size = spans.pop(0)
    lines = text.splitlines(keepends=True)
    middle = "".join(lines[lo:hi]).rstrip("\n")
    return "".join(lines[:lo]), middle, "\n" + "".join(lines[hi:]), f"ast_{size}"


def code_lines(text):
    """(start offset, line) of lines with real code (not blank, not just a brace/comment)."""
    out, pos = [], 0
    for ln in text.split("\n"):
        s = ln.strip()
        if len(s) >= 6 and not s.startswith(("//", "#", "*", "/*")):
            out.append((pos, ln))
        pos += len(ln) + 1
    return out


def hole_midline(rng, text, lang, state):
    cl = code_lines(text)
    if not cl:
        return None
    start, ln = rng.choice(cl)
    indent = len(ln) - len(ln.lstrip())
    if len(ln) - indent < 6:
        return None
    col = rng.randint(indent + 1, len(ln) - 1)
    end = start + len(ln)
    extra = min(int(rng.expovariate(0.8)), 6)  # usually just the rest of the line
    for _ in range(extra):
        nxt = text.find("\n", end + 1)
        if nxt == -1:
            break
        end = nxt
    return text[:start + col], text[start + col:end], text[end:], "midline"


def hole_span(rng, text, lang, state):
    if len(text) < 200:
        return None
    a = rng.randrange(0, len(text) - 20)
    n = min(int(rng.expovariate(1 / 150)) + 5, MAX_MIDDLE_CHARS)
    b = min(len(text), a + n)
    if not text[a:b].strip():
        return None
    return text[:a], text[a:b], text[b:], "span"


def hole_empty(rng, text, lang, state):
    cl = code_lines(text)
    if not cl:
        return None
    start, ln = rng.choice(cl)
    cut = start + len(ln)  # end of a complete line: nothing is missing
    return text[:cut], "", text[cut:], "empty"


def file_row(rng, text):
    """A chunk of the file split pretraining-style; loss on every token."""
    lines = text.splitlines(keepends=True)
    first = rng.randrange(0, max(1, len(lines) - 5))
    chunk = cut_suffix("".join(lines[first:]), FILE_CHUNK_CHARS)
    if len(chunk) < 200:
        return None
    a, b = sorted(rng.sample(range(len(chunk)), 2))
    return chunk[:a], chunk[a:b], chunk[b:]


PICKERS = {"ast": hole_ast, "midline": hole_midline, "span": hole_span, "empty": hole_empty}


def build_repo(job: dict) -> dict:
    """All rows for one repo (runs in a worker process)."""
    repo, root, budget, seed = job["repo"], Path(job["root"]), job["budget"], job["seed"]
    rng = random.Random(seed)
    all_files = repo_files(root, job["src"])
    files = {k: v for k, v in all_files.items() if norm_hash(v) not in job["banned"]}
    if not files:
        return {"repo": repo, "rows": [], "files": 0, "heldout_copies": len(all_files)}
    graph = import_graph(files)
    callers = collections.defaultdict(set)
    for f, deps in graph.items():
        for d in deps:
            callers[d].add(f)
    names_ctx = None
    if job.get("ctx") == "names":
        from ctx_gather import RepoContext  # imported here: ctx_gather imports this module

        names_ctx = RepoContext(files)
    ctx_share, ctx_chars, tag = job.get("ctx_share", CTX_SHARE), job.get("ctx_chars", CTX_CHARS), job.get("tag", "v04")
    paths = sorted(files)
    weights = [math.sqrt(files[p].count("\n") + 1) for p in paths]  # big files get more rows, but not linearly
    states = {p: {} for p in paths}
    kinds, kw = list(KINDS), list(KINDS.values())
    rows, tries, seen = [], 0, set()
    while len(rows) < budget and tries < budget * 6:
        tries += 1
        rel = rng.choices(paths, weights)[0]
        text, lang = files[rel], EXT_LANG[Path(rel).suffix]
        kind = rng.choices(kinds, kw)[0]
        pre_n, suf_n = window_sizes(rng, kind)
        if kind == "file":
            got = file_row(rng, text)
            if not got:
                continue
            prefix, middle, suffix = got
            ctx, hole, loss = "", "file", "all"
        else:
            got = PICKERS[kind](rng, text, lang, states[rel])
            if not got:
                continue
            full_pre, middle, full_suf, hole = got
            if len(middle) > MAX_MIDDLE_CHARS or (kind != "empty" and not middle.strip()):
                continue
            if kind == "empty" and not full_suf.strip():
                continue  # nothing after the cursor: "stop" wouldn't clearly be right
            prefix, suffix = cut_prefix(full_pre, pre_n), cut_suffix(full_suf, suf_n)
            ctx = ""
            if rng.random() < ctx_share:
                if names_ctx:  # the editor has the file without the missing code; the prompt shows the window
                    cur = len(full_pre)
                    ctx = names_ctx.gather(rel, full_pre + full_suf, cur - len(prefix), cur + len(suffix), cur,
                                           ctx_chars)
                else:
                    ctx = context_block(rng, rel, files, graph, callers)
            loss = "middle"
        key = (rel, len(prefix), middle)
        if key in seen:
            continue
        seen.add(key)
        rows.append({"id": f"{tag}_{repo.replace('/', '__')}_{rel}_{len(rows)}", "category": f"quark_{tag}",
                     "repo": repo, "path": rel, "lang": lang, "hole": hole, "ctx": bool(ctx), "loss": loss,
                     "fim_prompt": f"{ctx}{FIM_PRE}{prefix}{FIM_SUF}{suffix}{FIM_MID}", "oracle_middle": middle})
    return {"repo": repo, "rows": rows, "files": len(files), "heldout_copies": len(all_files) - len(files)}


def load_repos(clones: Path) -> tuple[list[dict], set[str]]:
    """(training repos with their globs, normalized hashes of every held-out benchmark file)."""
    v03 = {json.loads(l)["repo"]: json.loads(l) for l in open("quark_repos.jsonl", encoding="utf-8") if l.strip()}
    out = []
    for l in open("quark_repos_v04_clean.jsonl", encoding="utf-8"):
        if l.strip():
            r = json.loads(l)
            out.append({**r, "set": "v04"})
    for repo, src in {**{k: c["src"] for k, c in REPOS.items()}, **SFT_ONLY}.items():
        if repo not in HELDOUT and repo in v03:
            out.append({**v03[repo], "src": src, "set": "v03", "ai_tool_topic": False})
    banned = set()
    for repo in HELDOUT:
        root = clones / repo.replace("/", "__")
        if root.is_dir() and repo in REPOS:
            banned |= {norm_hash(t) for t in repo_files(root, REPOS[repo]["src"]).values()}
    names = {r["repo"] for r in out}
    assert not names & set(HELDOUT), names & set(HELDOUT)
    return out, banned


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--clones", default=str(Path.home() / "quark_repos"))
    ap.add_argument("--rows", type=int, default=120_000)
    ap.add_argument("--repos", type=int, default=0, help="only the first N repos (smoke test)")
    ap.add_argument("--out", default="fim_v04.jsonl")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--ctx", choices=["imports", "names"], default="imports",
                    help="imports: v0.4's file skeletons; names: ctx_gather.py's editor-style context (v0.5)")
    ap.add_argument("--ctx-share", type=float, default=CTX_SHARE, help="hole rows that get repo context")
    ap.add_argument("--ctx-chars", type=int, default=CTX_CHARS, help="context budget (--ctx names)")
    ap.add_argument("--tag", default="v04", help="row id / category prefix")
    a = ap.parse_args()
    clones = Path(a.clones)
    repos, banned = load_repos(clones)
    print(f"{len(repos)} repos ({sum(r['set'] == 'v04' for r in repos)} v0.4 + {sum(r['set'] == 'v03' for r in repos)} "
          f"v0.3), {len(banned)} held-out file hashes banned")
    jobs = []
    for r in repos[:a.repos] if a.repos else repos:
        root = clones / r["repo"].replace("/", "__")
        head = git(root, "rev-parse", "HEAD").strip()
        if head != r["commit"]:
            print(f"!! {r['repo']}: clone is at {head[:10] or 'nothing'}, not {r['commit'][:10]}; skipped")
            continue
        lines = r.get("src_lines_checked") or r.get("src_lines") or 5000
        w = math.sqrt(lines) * LANG_WEIGHT.get(r["lang"], 1.0) * (AI_TOOL_WEIGHT if r.get("ai_tool_topic") else 1.0)
        jobs.append({"repo": r["repo"], "root": str(root), "src": r["src"], "w": w, "lang": r["lang"],
                     "banned": banned, "ctx": a.ctx, "ctx_share": a.ctx_share, "ctx_chars": a.ctx_chars,
                     "tag": a.tag})
    total_w = sum(j["w"] for j in jobs)
    for i, j in enumerate(jobs):
        j["budget"] = max(20, round(a.rows * j["w"] / total_w))
        j["seed"] = a.seed * 100_003 + i
    stats, n = {}, 0
    by = collections.Counter()
    with cf.ProcessPoolExecutor(a.workers) as ex, open(a.out, "w", encoding="utf-8") as f:
        for res in ex.map(build_repo, jobs):
            for row in res["rows"]:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
                by[(row["lang"], row["hole"])] += 1
                by[("ctx", row["ctx"])] += 1
            n += len(res["rows"])
            stats[res["repo"]] = {"files": res["files"], "rows": len(res["rows"]), "heldout_copies": res["heldout_copies"]}
            note = f"   !! {res['heldout_copies']} files copied from a held-out repo, skipped" if res["heldout_copies"] else ""
            print(f"  {res['repo']:50} {res['files']:5} files {len(res['rows']):6} rows   (total {n}){note}", flush=True)
    Path(a.out).with_suffix(".stats.json").write_text(json.dumps(
        {"rows": n, "by_lang_hole": {f"{k[0]}/{k[1]}": v for k, v in sorted(by.items(), key=str)}, "repos": stats},
        indent=1))
    langs = collections.Counter()
    holes = collections.Counter()
    for (k1, k2), v in by.items():
        if k1 != "ctx":
            langs[k1] += v
            holes[k2] += v
    print(f"\n{n} rows -> {a.out}\n  by language: {dict(langs)}\n  by kind: {dict(holes)}\n"
          f"  with repo context: {by[('ctx', True)]}\n"
          f"  files skipped as copies of held-out benchmark files: {sum(s['heldout_copies'] for s in stats.values())}")


if __name__ == "__main__":
    main()
